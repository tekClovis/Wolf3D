void cp_x_y(game_handler_t *g_h, int i)
{
    for (int y = 0; y < MAP_HEIGHT && i == 0; y++)
        for (int x = 0; x < MAP_WIDTH; x++)
            g_h->game->level.map[i][y][x] = map1[y][x];
    for (int y = 0; y < MAP_HEIGHT && i == 1; y++)
        for (int x = 0; x < MAP_WIDTH; x++)
            g_h->game->level.map[i][y][x] = map2[y][x];
    for (int y = 0; y < MAP_HEIGHT && i == 2; y++)
        for (int x = 0; x < MAP_WIDTH; x++)
            g_h->game->level.map[i][y][x] = map3[y][x];
}

bool init_level(game_handler_t *g_h)
{
    g_h->game->level.actual_level = 0;
    for (int i = 0; i < 3; i++)
        cp_x_y(g_h, i);
    return true;
}

bool load_map(game_handler_t *g_h , char *file)
{
    FILE *fd = NULL;
    ssize_t nb_read = 0;
    char path[256];

    snprintf(path, sizeof(path), "%s%s", g_h->game->actual_save, file);
    fd = fopen(path, "rb");
    if (fd == NULL)
        return init_level(g_h);
    nb_read = read(fd, &g_h->game->level, sizeof(level_t));
    fclose(fd);
    if (nb_read < sizeof(level_t))
        return init_level(g_h);
    return true;
}
